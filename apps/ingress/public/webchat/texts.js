/** The browser's language, if it is one Kelpie has; English otherwise. */
export function localeOf(language) {
  const primary = String(language || "")
    .toLowerCase()
    .split(/[-_]/)[0];
  const known = { pt: "pt-BR", es: "es", en: "en" };
  return Object.hasOwn(known, primary) ? known[primary] : "en";
}
